#!/usr/bin/env python3
"""Generate src/unicode_tables.inc: code-point ranges for \\p{L} (letters) and \\p{N} (numbers).

The GPT-2 pre-tokenizer regex needs these two Unicode classes. Instead of pulling in a
Unicode library, we dump the ranges once and compile them into the C++ code.
Only the Python standard library is needed.
"""
import sys
import unicodedata
from pathlib import Path


def ranges(prefix):
    """Merge consecutive code points whose general category starts with `prefix` into [lo, hi]."""
    out, start = [], None
    for cp in range(sys.maxunicode + 2):
        hit = cp <= sys.maxunicode and unicodedata.category(chr(cp)).startswith(prefix)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def emit(name, rs):
    body = ",\n".join("    {0x%X, 0x%X}" % r for r in rs)
    return "static const CodeRange %s[] = {\n%s\n};\n" % (name, body)


def main():
    dst = Path(__file__).resolve().parent.parent / "src" / "unicode_tables.inc"
    dst.parent.mkdir(exist_ok=True)
    text = "// Generated by scripts/gen_unicode_table.py (Unicode %s). Do not edit.\n" % unicodedata.unidata_version
    text += emit("kLetterRanges", ranges("L")) + "\n" + emit("kNumberRanges", ranges("N"))
    dst.write_text(text, encoding="utf-8")
    print("wrote", dst)


if __name__ == "__main__":
    main()
